"""Generate pc/ld/psx_globals.syms -- absolute PS1 addresses for every data symbol.

The globals model (docs/pc-port/PC-PORT-TODO.md section 4): instead of one
independent C variable per D_xxxx (which cannot alias overlapping names like
D_800EE740[4096] vs cal_kind_apr2, and has no initialized data), every data
symbol becomes an ABSOLUTE address inside a 2 MB PS1 RAM block that
pc/src/psx_ram.c mmaps at 0x80000000.  `ld --just-symbols` then resolves the
symbols to those addresses; the retail bytes (disks/dumps/ram.bin at boot,
the EXN overlays at scene load) populate the block.

Two symbol sources:
  * D_<8 hex> address-shaped tokens in the tree  -> cal_kind_apr2 = 0x800EE7A6;
  * landed DATA names from config/symbol_names.json (the renames of D_
    tokens, e.g. _svm_cur at 0x801315F0) -> _svm_cur = 0x801315F0;

Function symbols are NOT here: functions compile as real native code and the
function pointers stored in the data are relocated at load time
(pc/src/psx_ram.c's reloc pass).

Usage:  python3 pc/tools/gen_psx_globals.py [--out pc/ld/psx_globals.syms]
Deterministic: sorted output, idempotent.
"""
import argparse
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pc_paths import DECOMP, MONOREPO_DECOMP, spell  # noqa: E402
ADDR_RE = re.compile(r'D_([0-9A-Fa-f]{8})\b')
KEY_RE = re.compile(r'(?:0x)?([0-9A-Fa-f]{8})')
SCAN_DIRS = ('src', 'asm', 'pc/src', 'pc/hal', 'pc/include', 'include', 'config')


def collect_tokens():
    """Every D_<8 hex> token in the tree source (the address is in the name)."""
    out = subprocess.run(['git', 'grep', '-oh', r'\bD_[0-9A-Fa-f]\{8\}\b', '--']
                         + [d for d in SCAN_DIRS if os.path.isdir(os.path.join(ROOT, d))],
                         capture_output=True, text=True, cwd=ROOT).stdout
    if not MONOREPO_DECOMP:
        # the decompiled C, asm, include/ and config/ are toki1-decomp's
        out += subprocess.run(['git', 'grep', '-oh', r'\bD_[0-9A-Fa-f]\{8\}\b', '--']
                              + [d for d in ('src', 'asm', 'include', 'config')
                                 if (DECOMP / d).is_dir()],
                              capture_output=True, text=True, cwd=DECOMP).stdout
    names = set(m.group(0) for m in re.finditer(r'D_[0-9A-Fa-f]{8}', out))
    return {n: int(n[2:], 16) for n in names}


def collect_landed_data():
    """Landed data names from the ledger (the renames of address tokens)."""
    with open(os.path.join(ROOT, spell('config/symbol_names.json'))) as fh:
        syms = json.load(fh)['symbols']
    out = {}
    for key, e in syms.items():
        if e.get('kind') != 'data' or not e.get('landed'):
            continue
        m = KEY_RE.fullmatch(key.split(':')[-1])
        if not m:
            continue
        name = e['name']
        if re.fullmatch(r'D_[0-9A-Fa-f]{8}', name):
            continue  # address-shaped: already collected
        out[name] = int(m.group(1), 16)
    return out


# The pilot scope: the overlay window (the mapped 0x80132000-0x80232000).
# The main-data band (0x800BB3C0-0x80132000) needs the full RAM model first
# (see the note in pc/src/main.c about why the broad mmap was deferred).
WIN_LO, WIN_HI = 0x80132000, 0x80232000


def collect_main_fnmap():
    """The main address -> native C symbol map (the function-pointer relocation).
    From the registry: every function's address and its C symbol name."""
    with open(os.path.join(ROOT, spell('config/level3_functions.json'))) as fh:
        fns = json.load(fh)['functions']
    out = []
    for f in fns:
        m = KEY_RE.fullmatch(f['address'].replace('0x', ''))
        if m:
            out.append((int(m.group(1), 16), f['name']))
    return sorted(out)


def emit_main_fnmap(entries, path_h='pc/src/psx_main_map.h', path_c='pc/src/psx_main_map.c'):
    """psx_main_map.c/.h: the {ps1, native} map in its OWN TU (so the function
    declarations cannot conflict with the real headers)."""
    decls = []
    rows = []
    for addr, name in entries:
        if not re.fullmatch(r'[A-Za-z_]\w*', name):
            continue
        decls.append('extern void %s() __attribute__((weak));' % name)
        rows.append('    { 0x%08Xu, (void *)%s },' % (addr, name))
    body = ['/* GENERATED by pc/tools/gen_psx_globals.py.  Own TU: the declarations',
            ' * here cannot conflict with the real headers.  Do not edit. */',
            '#include "psx_main_map.h"', ''] + decls + ['',
            'const PsxFnMap g_psx_main_map[] = {'] + rows + ['};', '',
            'const int g_psx_main_map_n = (int)(sizeof g_psx_main_map / sizeof g_psx_main_map[0]);']
    hdr = ['/* GENERATED by pc/tools/gen_psx_globals.py. */',
           '#ifndef PSX_MAIN_MAP_H', '#define PSX_MAIN_MAP_H',
           'typedef struct { unsigned int ps1; void *native; } PsxFnMap;',
           'extern const PsxFnMap g_psx_main_map[];',
           'extern const int g_psx_main_map_n;', '#endif']
    for path, text in ((path_c, body), (path_h, hdr)):
        with open(os.path.join(ROOT, path), 'w') as fh:
            fh.write('\n'.join(text) + '\n')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default='pc/ld/psx_globals.syms')
    ap.add_argument('--fnmap', default='pc/src/psx_main_map.h')
    ap.add_argument('--all', action='store_true',
                    help='emit every data symbol (the full model), not just the window')
    args = ap.parse_args()

    syms = collect_tokens()
    syms.update(collect_landed_data())
    if not args.all:
        syms = {n: a for n, a in syms.items() if WIN_LO <= a < WIN_HI}
    fns = collect_main_fnmap()
    emit_main_fnmap(fns)
    print('gen_psx_globals: %d fn-map entries -> pc/src/psx_main_map.{c,h}' % len(fns))

    lines = ['/* pc/ld/psx_globals.syms -- GENERATED by pc/tools/gen_psx_globals.py.',
             ' * Absolute PS1 addresses for the data symbols (the globals model).',
             ' * Linked with -Wl,--just-symbols=...; the RAM block lives at',
             ' * 0x80000000 (pc/src/psx_ram.c).  Do not edit; regenerate. */']
    for name in sorted(syms, key=lambda n: (syms[n], n)):
        lines.append('%s = 0x%08X;' % (name, syms[name]))

    out_path = os.path.join(ROOT, args.out)
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, 'w') as fh:
        fh.write('\n'.join(lines) + '\n')
    print('gen_psx_globals: %d symbols -> %s' % (len(syms), args.out))
    return 0


if __name__ == '__main__':
    sys.exit(main())
