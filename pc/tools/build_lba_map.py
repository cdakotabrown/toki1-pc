"""
Enumerate all files in the PSX disc image (ISO 9660) and emit a static C
table mapping file paths to (LBA, byte size). Used by pc/hal/file_id.c
to resolve file_id values from cd_read_start2 calls into actual file
content (per-character archives, BS images, etc.).

Usage:
    python3 pc/tools/build_lba_map.py <disc.bin> <output.c>
"""
import struct
import sys
from pathlib import Path

SECTOR_SIZE = 2352  # raw mode-2 form-1 with sync+ECC

def read_sector_user(f, lba):
    """Read 2048 user data bytes from sector LBA (raw 2352-byte sectors)."""
    if lba < 0:
        raise ValueError('negative sector address')
    f.seek(lba * SECTOR_SIZE + 24)  # 12 sync + 4 header + 8 sub-header = 24
    data = f.read(2048)
    if len(data) != 2048:
        raise ValueError(f'truncated disc sector {lba}')
    return data

def read_dir(f, lba, size):
    """Walk an ISO 9660 directory and yield (name, lba, size) for each file."""
    sectors = (size + 2047) // 2048
    if not 0 < size <= 2 * 1024 * 1024:
        raise ValueError('ISO directory exceeds 2 MiB or is empty')
    data = b''.join(read_sector_user(f, lba + i) for i in range(sectors))[:size]
    off = 0
    while off < len(data):
        rec_len = data[off]
        if rec_len == 0:
            # Padding to next sector
            next_sector = (off // 2048 + 1) * 2048
            off = next_sector
            continue
        if rec_len < 34 or off + rec_len > len(data) or off % 2048 + rec_len > 2048:
            raise ValueError('invalid ISO directory record length')
        ext_lba = struct.unpack('<I', data[off+2:off+6])[0]
        ext_size = struct.unpack('<I', data[off+10:off+14])[0]
        flags = data[off+25]
        name_len = data[off+32]
        if name_len == 0 or 33 + name_len > rec_len:
            raise ValueError('invalid ISO directory name length')
        name = data[off+33:off+33+name_len].decode('ascii', errors='replace')
        # Strip ;1 version suffix
        if ';' in name:
            name = name.split(';')[0]
        yield (name, ext_lba, ext_size, flags & 0x02 != 0)
        off += rec_len

def walk(f, lba, size, prefix='', seen=None, depth=0):
    """Recursively walk the ISO directory tree."""
    if seen is None:
        seen = set()
    if lba in seen or depth > 32 or len(seen) >= 4096:
        raise ValueError('cyclic or excessive ISO directory tree')
    seen.add(lba)
    files = []
    for name, child_lba, child_size, is_dir in read_dir(f, lba, size):
        if name in ('\x00', '\x01'):  # current/parent dir
            continue
        full = prefix + '/' + name if prefix else name
        if is_dir:
            files.extend(walk(f, child_lba, child_size, full, seen, depth + 1))
        else:
            files.append((full, child_lba, child_size))
        if len(files) > 100000:
            raise ValueError('too many ISO files')
    return files

def main(disc_path, out_path):
    with open(disc_path, 'rb') as f:
        # PVD at LBA 16
        pvd = read_sector_user(f, 16)
        if pvd[1:6] != b'CD001':
            raise ValueError(f'Not an ISO 9660: {pvd[1:6]!r}')
        root_lba = struct.unpack('<I', pvd[158:162])[0]
        root_size = struct.unpack('<I', pvd[166:170])[0]
        files = walk(f, root_lba, root_size)

    files.sort()
    with open(out_path, 'w') as out:
        out.write('/* Auto-generated by pc/tools/build_lba_map.py — do not edit. */\n')
        out.write('#include "../hal/file_id.h"\n\n')
        out.write(f'const FileLbaEntry g_file_lba_table[] = {{\n')
        for name, lba, size in files:
            esc = name.replace('\\', '\\\\').replace('"', '\\"')
            out.write(f'    {{ "{esc}", {lba}, {size} }},\n')
        out.write('};\n\n')
        out.write(f'const u32 g_file_lba_table_count = {len(files)};\n')
    print(f"wrote {len(files)} entries to {out_path}")

if __name__ == '__main__':
    if len(sys.argv) != 3:
        print(__doc__); sys.exit(1)
    main(sys.argv[1], sys.argv[2])
