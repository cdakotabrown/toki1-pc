"""Generate pc/include/game/sony_bios_alias.h from config/symbol_names.json.

The retail main binary carries Sony's libc names: one 16-byte BIOS thunk per
kernel entry (strncpy, printf, rand, open, read, ...) and a few in-image libc
bodies (memset, sprintf).  Since the 2026-10-08 renames the game C calls
them by those names.  On the PC host those names belong to libc, so the game
translation units -- and only those (pc/Makefile force-includes the header for
src/main/** and the overlay modules) -- see a macro that maps each such name
back to its address name, which src/main/pc-port/bios_trampolines.c (or the
in-image C itself, compiled under the same macro) defines.  HAL and pc/src
code is compiled without the header and keeps the real libc.

The rule is mechanical: a LANDED main-scope function name that the host libc /
libm exports (or that is a C-standard macro such as abs / setjmp) is aliased.
Re-run after a rename lands a new libc-named function:

    python3 pc/tools/gen_sony_bios_alias.py            # rewrite the header
    python3 pc/tools/gen_sony_bios_alias.py --check    # exit 1 if it is stale

pc/tools/sync_symbol_names.py imports host_libc_names() so that the same set
of names is left address-named in the port when it replays the renames.
"""
import glob
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pc_paths import DECOMP  # noqa: E402
sys.path.insert(0, str(DECOMP / 'tools' / 'analysis'))
import symbol_names as SN  # noqa: E402

HEADER = os.path.join(ROOT, 'pc/include/game/sony_bios_alias.h')
LIBS = ('/lib/x86_64-linux-gnu/libc.so.6', '/lib/x86_64-linux-gnu/libm.so.6',
        '/usr/lib/x86_64-linux-gnu/libc.so.6', '/usr/lib/x86_64-linux-gnu/libm.so.6',
        '/lib64/libc.so.6', '/lib64/libm.so.6')
# C-standard / POSIX names that are macros or builtins rather than exports on
# some hosts, plus the BSD string names glibc keeps.
MACRO_NAMES = {'abs', 'labs', 'setjmp', 'longjmp', 'alloca', 'bcopy', 'bzero', 'bcmp',
               'index', 'rindex', 'memcpy', 'memset', 'memmove', 'memchr', 'memcmp',
               'strlen', 'strcpy', 'strncpy', 'strcat', 'strncat', 'strcmp', 'strncmp',
               'strchr', 'strrchr', 'printf', 'sprintf', 'puts', 'putchar', 'getchar',
               'rand', 'srand', 'exit', 'abort', 'atoi', 'atol', 'strtol', 'qsort',
               'bsearch', 'open', 'close', 'read', 'write', 'lseek', 'malloc', 'free',
               'calloc', 'realloc', 'toupper', 'tolower', 'isdigit', 'isalpha', 'isspace'}

_cache = None


def host_libc_names():
    """exported symbol names of the host libc/libm, plus the macro names."""
    global _cache
    if _cache is not None:
        return _cache
    names = set(MACRO_NAMES)
    for lib in LIBS:
        if not os.path.exists(lib):
            continue
        out = subprocess.run(['nm', '-D', '--defined-only', lib], capture_output=True, text=True).stdout
        for line in out.splitlines():
            parts = line.split()
            if len(parts) >= 3:
                names.add(parts[2].split('@')[0])
    _cache = names
    return names


def aliases():
    """sorted [(name, address)] of landed main-scope functions whose name is a host libc name."""
    doc = SN.load_names()
    libc = host_libc_names()
    out = []
    for key, e in doc['symbols'].items():
        if ':' in key or e.get('kind') != 'func' or not e.get('landed'):
            continue
        if e['name'] in libc and not SN.is_address_name(e['name']):
            out.append((e['name'], int(key, 16)))
    return sorted(out, key=lambda t: t[1])


def render():
    lines = [
        '/* sony_bios_alias.h -- scoped aliases for the Sony libc names (PC port).',
        ' *',
        ' * GENERATED by pc/tools/gen_sony_bios_alias.py from config/symbol_names.json;',
        ' * do not edit by hand, re-run the generator after a naming pass.',
        ' *',
        ' * The retail main binary carries one 16-byte Psy-Q LIBAPI/LIBC/LIBCARD thunk',
        ' * per kernel entry (`addiu t2,zero,0xA0/0xB0; jr t2; addiu t1,zero,N`) and a',
        ' * few in-image libc bodies (memset, sprintf).  They are named by Sony\'s own',
        ' * symbol, and since 2026-10-08 the PS1 tree uses those names: the matched',
        ' * game code calls `printf(...)`, `rand()`, `read(fd, ...)`, `memset(...)`.',
        ' *',
        ' * On PC those names belong to libc / POSIX.  The PC port never forwarded the',
        ' * thunks to libc blindly (src/main/pc-port/bios_trampolines.c: some are',
        ' * no-ops, the memory-card file calls go to pc/hal/memcard.c), and that must',
        ' * not change behind the rename.  So the game translation units -- and only',
        ' * those -- see this header (pc/Makefile force-includes it after',
        ' * pc/include/game/types.h for src/main/**, pc/src/overlay_* and the overlay',
        ' * sources), which maps each Sony libc name back to its address name.  The',
        ' * in-image bodies (src/main/matched/memset.c, sprintf.c) are game TUs too,',
        ' * so the macro renames their definitions along with their callers.  HAL and',
        ' * pc/src code is compiled without it and keeps the real libc.',
        ' *',
        ' * The system headers are included first so that a later #include <stdio.h>',
        ' * inside a game TU cannot be rewritten by the macros.',
        ' *',
        ' * Intentional PS1/PC divergence, documented here as the PC-port policy asks:',
        ' * the PS1 build calls the kernel; the PC build calls the trampoline of the',
        ' * same address, exactly as before the rename.',
        ' */',
        '#ifndef SONY_BIOS_ALIAS_H',
        '#define SONY_BIOS_ALIAS_H',
        '',
        '#include <stdio.h>',
        '#include <stdlib.h>',
        '#include <string.h>',
        '#include <strings.h>',
        '#include <setjmp.h>',
        '#include <unistd.h>',
        '#include <fcntl.h>',
        '',
    ]
    for name, addr in aliases():
        lines.append(f'#define {name:<12}func_{addr:08X}')
    lines += ['', '#endif /* SONY_BIOS_ALIAS_H */', '']
    return '\n'.join(lines)


def main():
    text = render()
    if '--check' in sys.argv:
        cur = open(HEADER).read() if os.path.exists(HEADER) else ''
        if cur != text:
            print(f'{os.path.relpath(HEADER, ROOT)} is stale: re-run {os.path.relpath(__file__, ROOT)}')
            return 1
        print('sony_bios_alias.h up to date')
        return 0
    open(HEADER, 'w').write(text)
    print(f'wrote {os.path.relpath(HEADER, ROOT)}: {len(aliases())} aliases')
    return 0


if __name__ == '__main__':
    sys.exit(main())
