"""retail_init_transform.py -- rewrite pc/src/missing_globals_gen.c so that
no initialiser is a copy of retail bytes (pc/include/pc_retail_init.h).

    python3 pc/tools/retail_init_transform.py [--check] [--exe disks/SLPS_000.65]

gen_missing_globals.py now writes this form itself; this tool converts an
existing generated file without re-running the generator (which needs a
link log and rewrites the alias script too).  Each byte / halfword / word
array initialiser and each `static u8 blob_ADDR[]` becomes a zero definition
plus a pc_retail_init[] row (address, size), filled from the player's
PSX.EXE at start-up.  Before it rewrites anything it checks that every
removed initialiser is exactly the executable's bytes at that address, so
the run-time fill gives each object the value it had; a mismatch is an
error and nothing is written.  --check: exit 1 when the file still has a
retail-byte array initialiser.
"""
import argparse
from pathlib import Path
import re
import struct
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from pc_paths import disc_input  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
GEN = ROOT / 'pc/src/missing_globals_gen.c'
TEXT_START, FILE_BASE = 0x80041000, 0x800
TYPES = {'u8': (1, 'B'), 's8': (1, 'b'), 'char': (1, 'b'), 'u16': (2, 'H'), 's16': (2, 'h'),
         'short': (2, 'h'), 'unsigned short': (2, 'H'), 'u32': (4, 'I'), 's32': (4, 'i'),
         'int': (4, 'i'), 'unsigned int': (4, 'I'), 'unsigned': (4, 'I')}
BLOB = re.compile(r'^static u8 (blob_([0-9A-F]{8}))\[(\d+)\] = \{([^}]*)\}; /\* retail 0x[0-9A-F]{8} \*/$')
ARRAY = re.compile(r'^((?:unsigned (?:short|int)|unsigned|[a-z0-9]+)) ([A-Za-z_]\w*)\[(\d+)\] = \{([^}]*)\}; '
                   r'/\* (0x[0-9a-f]+) retail \*/$')
HEADER = ('/* Generated by pc/tools/gen_missing_globals.py -- retail initial values come from the '
          "player's PSX.EXE at run time (pc_retail_init) */")


def ints(body):
    return [int(v, 0) for v in body.split(',')] if body.strip() else []


def transform(text, img):
    out, rows = [], []

    def image(addr, n):
        off = addr - TEXT_START + FILE_BASE
        if not (0 <= off and off + n <= len(img)):
            raise ValueError(f'0x{addr:08X}+{n} lies outside the executable image')
        return img[off:off + n]
    for line in text.splitlines():
        m = BLOB.match(line)
        if m:
            name, addr, n = m.group(1), int(m.group(2), 16), int(m.group(3))
            if bytes(ints(m.group(4))) != image(addr, n):
                raise ValueError(f'{name}: initialiser differs from the executable')
            out.append(f'static u8 {name}[{n}]; /* retail 0x{addr:08X}, loaded at run time */')
            rows.append((name, addr, n))
            continue
        m = ARRAY.match(line)
        if m and m.group(1) in TYPES:
            ty, name, count, body, addr = m.group(1), m.group(2), int(m.group(3)), m.group(4), int(m.group(5), 16)
            es, fmt = TYPES[ty]
            vals = ints(body)
            if len(vals) != count:
                raise ValueError(f'{name}: {len(vals)} values for [{count}]')
            want = image(addr, count * es)
            # the generator spells some signed elements unsigned (char 137):
            # compare the bit patterns
            got = b''.join(struct.pack('<' + fmt.upper(), v & ((1 << (8 * es)) - 1)) for v in vals)
            if got != want:
                raise ValueError(f'{name}: initialiser differs from the executable')
            out.append(f'{ty} {name}[{count}]; /* {m.group(5)} retail, loaded at run time */')
            rows.append((name, addr, count * es))
            continue
        out.append(line)
    if out and out[0].startswith('/* Generated by pc/tools/gen_missing_globals.py'):
        out[0] = HEADER
    out += ['', '/* The initial values above that are retail bytes: copied from the',
            " * player's own PSX.EXE at start-up (pc/src/retail_init.c). */",
            '#include "pc_retail_init.h"', 'const PcRetailInit pc_retail_init[] = {']
    out += [f'    {{ {n}, 0x{a:08X}, {s} }},' for n, a, s in sorted(set(rows), key=lambda r: (r[1], r[0]))]
    out += ['    { 0, 0, 0 }', '};', f'const unsigned pc_retail_init_count = {len(set(rows))};']
    return '\n'.join(out) + '\n', rows


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--exe', default=str(disc_input('disks/SLPS_000.65')))
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args(argv)
    text = GEN.read_text()
    if a.check:
        left = [l for l in text.splitlines() if BLOB.match(l) or (ARRAY.match(l) and ARRAY.match(l).group(1) in TYPES)]
        print(f'retail_init_transform: {len(left)} retail-byte array initialiser(s) left')
        return 1 if left else 0
    if 'pc_retail_init[]' in text:
        print('retail_init_transform: already transformed')
        return 0
    new, rows = transform(text, Path(a.exe).read_bytes())
    GEN.write_text(new)
    print(f'retail_init_transform: {len(rows)} initialisers -> run-time fill ({sum(r[2] for r in rows)} bytes)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
