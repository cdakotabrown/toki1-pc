"""Write the save-state inventory of a build (pc/hal/dbg_state.c).

A save state holds the project's own native data objects by name, never the
host libraries' (libc, the C++ runtime, SDL and winpthreads where they are
linked in statically).  The executable's symbol table cannot tell them apart
by itself: ELF and PE both record the source file of a STATIC, but a GLOBAL
carries no file.  This lists, from the very objects the executable is linked
from (every pc/build/obj/*.o, the translation and UI-font objects, the SPU
core archive), the source files they were compiled from and the global data
symbols they define, as C:

    const char *const pc_state_inv_files[];    sorted, pc_state_inv_nfiles
    const char *const pc_state_inv_globals[];  sorted, pc_state_inv_nglobals
    const char *const pc_state_inv_global_files[];   each global's source file

dbg_state.c saves a static when its file is listed and a global when its
name is (the KEEP_FILES rule then applies to the global's file too); pc/tools/test_state_inventory.py checks the result against the
linked executable (every writable byte is accounted for).

    gen_state_inventory.py --nm NM --out FILE.c OBJECT|ARCHIVE|@LIST ...
"""
import argparse
import os
import re
import subprocess
import sys

SOURCE = re.compile(r'\.(c|cc|cpp|cxx|S|s)$')
# nm types of a defined global data object: initialised (D), zero (B),
# small (G/S), weak object (V), GNU unique (u), common (C)
GLOBAL_DATA = set('DBGSVuC')


def expand(args):
    out = []
    for a in args:
        if a.startswith('@'):
            with open(a[1:]) as fh:
                out += fh.read().split()
        else:
            out.append(a)
    return out


def scan(nm, files):
    """-> (source files, {global data name: source file}) of FILES"""
    sources, globals_ = set(), {}
    seen_file = {}
    pending = []
    for i in range(0, len(files), 400):
        chunk = files[i:i + 400]
        r = subprocess.run([nm, '-A', '-a', '--defined-only'] + chunk, capture_output=True,
                           text=True)
        if r.returncode:
            sys.exit(f'gen_state_inventory: {nm} failed: {r.stderr[:2000]}')
        for line in r.stdout.splitlines():
            # "obj.o:VALUE T NAME" or "lib.a:member.o:VALUE T NAME"
            head, _, rest = line.rpartition(':')
            parts = rest.split(None, 2)
            if len(parts) == 3:
                _value, typ, name = parts
            elif len(parts) == 2:
                typ, name = parts
            else:
                continue
            if typ in ('a', '?') and SOURCE.search(name):
                # the object's source file record (ELF FILE, COFF .file):
                # the first one names the object
                if head not in seen_file:
                    seen_file[head] = name
                    sources.add(os.path.basename(name))
            elif typ in GLOBAL_DATA:
                pending.append((head, name))
    for head, name in pending:
        src = os.path.basename(seen_file.get(head, ''))
        # a weak/common object defined in several files: the first file wins
        globals_.setdefault(name, src)
    return sources, globals_


def c_list(name, items):
    out = [f'const char *const {name}[] = {{']
    for s in items:
        out.append('    "%s",' % s.replace('\\', '\\\\').replace('"', '\\"'))
    if not items:
        out.append('    0,')
    out.append('};')
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--nm', default='nm')
    ap.add_argument('--out', required=True)
    ap.add_argument('files', nargs='+')
    a = ap.parse_args()
    files = [f for f in expand(a.files) if f.endswith(('.o', '.a'))]
    sources, globals_ = scan(a.nm, files)
    files_sorted = sorted(sources, key=lambda s: s.encode())
    globals_sorted = sorted(globals_, key=lambda s: s.encode())
    lines = ['/* state_inventory.c -- generated by pc/tools/gen_state_inventory.py from the',
             ' * objects this executable is linked from; do not edit.  pc/hal/dbg_state.c',
             ' * saves a static of a listed file and a listed global. */']
    lines += c_list('pc_state_inv_files', files_sorted)
    lines.append(f'const int pc_state_inv_nfiles = {len(files_sorted)};')
    lines += c_list('pc_state_inv_globals', globals_sorted)
    lines.append(f'const int pc_state_inv_nglobals = {len(globals_sorted)};')
    lines += c_list('pc_state_inv_global_files', [globals_[g] for g in globals_sorted])
    text = '\n'.join(lines) + '\n'
    old = None
    if os.path.exists(a.out):
        with open(a.out) as fh:
            old = fh.read()
    if old != text:
        os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
        with open(a.out + '.tmp', 'w') as fh:
            fh.write(text)
        os.replace(a.out + '.tmp', a.out)
    print(f'STATE INVENTORY {len(files_sorted)} files, {len(globals_sorted)} global data objects '
          f'from {len(files)} inputs')
    return 0


if __name__ == '__main__':
    sys.exit(main())
