"""Generate pc/src/layout_aliases.ld: PS1 memory layout for the globals that
the game addresses BOTH by name and by offset from a containing object.

On the PS1 `screen_w` (0x800EE760) is the base of the game-state block and
the matched C reads its fields both ways: `now_step`, `icon_num`,
`frame_counter` by name, and `screen_w[3949]` (= icon_num),
`base[0x110F]` (the _main exit flag), `s0 != &schedule_buf_end` (a loop
bound 0x80 bytes past the base) by offset.  pc/src/globals.c defines each
name as its own C variable, so on the PC the two spellings were DIFFERENT
memory: `icon_disp_switch` counted the wrong slots, `schedule_girls_gakko`
walked off the end of `screen_w` looking for `&schedule_buf_end` (scene 48's
crash), `get_CD_State2()` returned a `cd_state2` that the matched CD queue
worker (which writes `cdq_head.flags`, the same byte on the PS1) never set.

This script emits one linker-script assignment per contained symbol,
    schedule_buf_end = screen_w + 0x80;
which makes the name an alias of the container's storage at its retail
offset.  A plain `sym = expr;` in a linker script overrides a definition in
an input object (verified with GNU ld 2.4x: the object's storage is left
unused and every reference resolves to the assigned address), so the C
definitions in pc/src/globals.c need no edit; their initialisers are lost,
which is correct for BSS (the retail values are zero) and is checked here
for the .data containers.

Containers are listed explicitly (CONTAINERS below) with their retail
address and size; the members come from config/symbol_names.json (every
main-scope data symbol strictly inside the container's extent).  Sizes in
symbol_names.json are often a guess (screen_w is recorded as 2), so they are
not used for the containers themselves.  When pc/build/tokimeki-pc exists
the script checks that the PC definition of each container is at least as
large as the retail extent it stands for.

Usage:
    python3 pc/tools/gen_layout_aliases.py            # writes pc/src/layout_aliases.ld
    python3 pc/tools/gen_layout_aliases.py --check    # exit 1 if the file is stale
"""
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pc_paths import spell  # noqa: E402
OUT = os.path.join(ROOT, 'pc/src/layout_aliases.ld')
BIN = os.path.join(ROOT, 'pc/build/tokimeki-pc')

# name, retail address, retail size (bytes), why
CONTAINERS = [
    ('screen_w',   0x800EE760, 0x4000,
     'game-state block: the matched C indexes it by byte offset (screen_w[3949] == icon_num, '
     'base[0x110F], &schedule_buf_end); pc/src/globals.c defines it as s16[8192]'),
    ('class_w',    0x801271B0, 10880,
     '160 sprite slots x 68 bytes; cursor_cw_* / bustup_cw_* / cwNN_* are slot fields'),
    ('cdq_head',   0x800E8DA0, 4,
     'CD queue control (matched cdq_command_process.c: head, tail, flags, phase); '
     'cdq_tail / cd_state2 / cd_head_pos are its bytes -- get_CD_State2() reads flags'),
    ('cdq_result', 0x800E9228, 8,
     'CD queue result (res, status, count); cd_state / cd_reads are its bytes -- '
     'get_CD_State() / get_reads() read them'),
    ('gSDInfo',    0x8012DD80, 80,
     'sound driver state block (serial_cmd.c declares the struct; other files name its fields)'),
]


def main():
    check = '--check' in sys.argv
    syms = json.load(open(os.path.join(ROOT, spell('config/symbol_names.json'))))['symbols']
    data = {}
    for k, v in syms.items():
        if ':' in k or v.get('kind') != 'data':
            continue
        data[int(k, 16)] = v['name']
    lines = ['/* Generated by pc/tools/gen_layout_aliases.py -- do not edit.',
             ' * Each assignment makes a named global an alias of its retail offset inside',
             ' * the object that contains it on the PS1 (see the generator docstring). */']
    total = 0
    pc_sizes = {}
    if os.path.exists(BIN):
        try:
            out = subprocess.run(['nm', '-S', BIN], capture_output=True, text=True).stdout
            for line in out.splitlines():
                parts = line.split()
                if len(parts) == 4:
                    pc_sizes[parts[3]] = int(parts[1], 16)
        except OSError:
            pass
    for name, base, size, why in CONTAINERS:
        members = sorted((a - base, n) for a, n in data.items() if base < a < base + size and n != name)
        if name in pc_sizes and pc_sizes[name] < size:
            print(f'[layout] WARNING: PC definition of {name} is {pc_sizes[name]} bytes, '
                  f'retail extent {size}: members past the end would alias other storage',
                  file=sys.stderr)
        lines.append('')
        lines.append(f'/* {name} @ 0x{base:08X}, {size} bytes: {why} ({len(members)} members) */')
        for off, n in members:
            lines.append(f'{n} = {name} + 0x{off:X};')
            total += 1
    text = '\n'.join(lines) + '\n'
    if check:
        old = open(OUT).read() if os.path.exists(OUT) else ''
        if old != text:
            print(f'{OUT} is stale: rerun pc/tools/gen_layout_aliases.py', file=sys.stderr)
            return 1
        print(f'{OUT} up to date ({total} aliases)')
        return 0
    with open(OUT, 'w') as fh:
        fh.write(text)
    print(f'wrote {OUT}: {total} aliases in {len(CONTAINERS)} containers')
    return 0


if __name__ == '__main__':
    sys.exit(main())
