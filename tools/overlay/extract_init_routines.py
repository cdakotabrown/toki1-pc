#!/usr/bin/env python3
"""Extract overlay init-region leaf routines as PC-port C source.

Each .EXN overlay has a region from 0x80132000 up to its first extracted
function. That region is a chain of tiny init routines (lui/ori/sw
patterns) that populate dispatch-table globals at 0x8014XXXX / 0x80155E__
with PS1 code addresses. The existing overlay extractor DOES catch them
via gap scanning, but they were never decompiled into src/overlay/<OV>/
for most overlays — so on PC those func_8013XXXX calls hit empty stubs
and the dispatch-table globals stay zero.

This tool emits a single `<OV>_init_routines.c` per overlay under
`src/main/pc-port/overlay_inits/`. Each file defines one C function per
init routine that performs the equivalent stores (PS1 addresses kept
as-is — callers that *read* these globals see non-zero; callers that
dereference them as code still crash, but at least the "init was called"
flag semantics are preserved, which unblocks a class of state-machine
checks).

Scope deliberately narrow: only emits routines whose address is BELOW
the first existing src/overlay/<OV>/func_8013XXXX.c file. Does not
touch .s/.c files under asm/overlay or src/overlay.
"""
import os
import struct
import sys
from pathlib import Path

LOAD_ADDR = 0x80132000
REPO = Path(__file__).resolve().parents[2]
EXN_DIR = REPO / 'build/translation/disc_extract/CDROM/EXEDIR'
OUT_DIR = REPO / 'pc/src/overlay_inits'
FILE_PREFIX = 'overlay_init_'
sys.path.insert(0, str(REPO / 'tools'))
from repo_paths import DECOMP  # noqa: E402  (src/overlay is toki1-decomp's)
OVERLAY_SRC = DECOMP / 'src/overlay'


def first_extracted_addr(ov):
    d = OVERLAY_SRC / ov
    if not d.is_dir():
        return None
    addrs = []
    for p in d.glob('func_8013*.c'):
        try:
            addrs.append(int(p.stem.split('_')[1], 16))
        except (ValueError, IndexError):
            pass
    return min(addrs) if addrs else None


def find_leaf_routines(data, limit):
    """Walk 0..limit, find runs that end with `jr ra` (0x03E00008)."""
    funcs = []
    start = 0
    # Skip leading zeros
    while start < limit and struct.unpack_from('<I', data, start)[0] == 0:
        start += 4
    i = start
    cur = start
    while i < limit:
        insn = struct.unpack_from('<I', data, i)[0]
        if insn == 0x03E00008:  # jr ra
            end = i + 8  # include delay slot
            if end <= limit and end - cur >= 8:
                funcs.append((cur, end - cur))
            # Skip trailing zero padding
            next_start = end
            while next_start < limit and struct.unpack_from('<I', data, next_start)[0] == 0:
                next_start += 4
            cur = next_start
            i = next_start
            continue
        i += 4
    return funcs


def decode_stores(data, offset, size):
    """Decode lui/ori/lui/sw (or lui/sw for immediate zero) patterns.
    Returns list of (target_addr, value) tuples for each completed store.
    Tracks per-register lui+ori state.
    """
    regs = {}  # reg_num -> current value
    stores = []
    end = offset + size
    for i in range(offset, end, 4):
        insn = struct.unpack_from('<I', data, i)[0]
        op = (insn >> 26) & 0x3F
        rs = (insn >> 21) & 0x1F
        rt = (insn >> 16) & 0x1F
        imm = insn & 0xFFFF
        simm = imm if imm < 0x8000 else imm - 0x10000
        if op == 0x0F:  # lui
            regs[rt] = imm << 16
        elif op == 0x0D:  # ori
            if rs in regs:
                regs[rt] = regs[rs] | imm
            else:
                regs[rt] = imm
        elif op == 0x09:  # addiu
            if rs in regs:
                regs[rt] = (regs[rs] + simm) & 0xFFFFFFFF
        elif op == 0x2B:  # sw $rt, simm($rs)
            if rs in regs:
                tgt = (regs[rs] + simm) & 0xFFFFFFFF
                val = regs.get(rt, 0) if rt != 0 else 0
                stores.append((tgt, val))
    return stores


def emit_overlay(ov, data, first_func_addr):
    limit = first_func_addr - LOAD_ADDR
    leafs = find_leaf_routines(data, limit)
    if not leafs:
        return 0, 0

    lines = [
        '/* Auto-generated by tools/overlay/extract_init_routines.py — DO NOT EDIT.',
        f' * Overlay: {ov}',
        f' * Region: 0x{LOAD_ADDR:08X}-0x{first_func_addr:08X}',
        f' * Routines: {len(leafs)}',
        ' *',
        ' * Each function replays the PS1 init-routine stores verbatim. Target',
        ' * addresses point into dispatch-table globals (typically 0x8014____ or',
        ' * 0x8015____); values are PS1 code addresses. PC mmap covers this range',
        ' * so writes succeed. Readers that treat the slot as a flag see non-zero;',
        ' * readers that call through the slot as a function pointer will still',
        ' * crash until the full vtable is ported.',
        ' */',
        '#include <stdint.h>',
        '',
        '#define STORE(addr, val) (*(volatile uint32_t *)(uintptr_t)(addr) = (uint32_t)(val))',
        '',
    ]
    emitted = 0
    total_stores = 0
    for offset, size in leafs:
        addr = LOAD_ADDR + offset
        stores = decode_stores(data, offset, size)
        if not stores:
            continue
        emitted += 1
        total_stores += len(stores)
        lines.append(f'/* 0x{addr:08X} — {size // 4} insns, {len(stores)} stores */')
        lines.append(f'void {ov}_func_{addr:08X}(void) {{')
        for tgt, val in stores:
            lines.append(f'    STORE(0x{tgt:08X}, 0x{val:08X});')
        lines.append('}')
        lines.append('')

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / f'{FILE_PREFIX}{ov}.c').write_text('\n'.join(lines) + '\n')
    return emitted, total_stores


def main():
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    summary = []
    for exn in sorted(EXN_DIR.glob('*.EXN')):
        ov = exn.stem
        first = first_extracted_addr(ov)
        if first is None:
            summary.append((ov, 'NO_SRC_OVERLAY', 0, 0))
            continue
        data = exn.read_bytes()
        n, s = emit_overlay(ov, data, first)
        summary.append((ov, f'0x{first:08X}', n, s))

    print(f'{"Overlay":<12} {"first_func":<12} {"routines":>8} {"stores":>8}')
    tot_r = 0
    tot_s = 0
    for ov, first, n, s in summary:
        print(f'{ov:<12} {first:<12} {n:>8} {s:>8}')
        tot_r += n
        tot_s += s
    print(f'{"TOTAL":<12} {"":<12} {tot_r:>8} {tot_s:>8}')


if __name__ == '__main__':
    main()
